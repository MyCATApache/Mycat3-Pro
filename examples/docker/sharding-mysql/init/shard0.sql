SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS db1_0 CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE db1_0;

CREATE TABLE orders_0 (
  id BIGINT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  status VARCHAR(16) NOT NULL,
  created DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE orders_1 LIKE orders_0;

CREATE TABLE tenant_order_0 (
  id BIGINT PRIMARY KEY,
  tenant_id VARCHAR(32) NOT NULL,
  note VARCHAR(128) NOT NULL,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE events_0 (
  id BIGINT PRIMARY KEY,
  event_type VARCHAR(32) NOT NULL,
  created DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE events_1 LIKE events_0;

CREATE TABLE dict (
  id BIGINT PRIMARY KEY,
  name VARCHAR(64) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE user_info (
  id BIGINT PRIMARY KEY,
  name VARCHAR(64) NOT NULL,
  profile VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
