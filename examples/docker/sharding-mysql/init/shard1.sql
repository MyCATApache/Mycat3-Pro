SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS db1_1 CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE db1_1;

CREATE TABLE orders_2 (
  id BIGINT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  status VARCHAR(16) NOT NULL,
  created DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE orders_3 LIKE orders_2;

CREATE TABLE tenant_order_1 (
  id BIGINT PRIMARY KEY,
  tenant_id VARCHAR(32) NOT NULL,
  note VARCHAR(128) NOT NULL,
  created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE events_2 (
  id BIGINT PRIMARY KEY,
  event_type VARCHAR(32) NOT NULL,
  created DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE events_3 LIKE events_2;

CREATE TABLE dict (
  id BIGINT PRIMARY KEY,
  name VARCHAR(64) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
